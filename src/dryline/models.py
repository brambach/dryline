"""Core types. The renderer only accepts TrailLine, and a TrailLine can't hold an uncited claim."""

from __future__ import annotations

import datetime as dt
from typing import Literal

from pydantic import (
    AwareDatetime,
    BaseModel,
    ConfigDict,
    Field,
    HttpUrl,
    model_validator,
)

Status = Literal["dry", "muddy", "snow", "closed", "unknown"]
STATUSES: tuple[Status, ...] = ("dry", "muddy", "snow", "closed", "unknown")
Aspect = Literal["N", "NE", "E", "SE", "S", "SW", "W", "NW", "mixed"]
Activity = Literal["hike", "run", "ride"]
# Official pages a trail's closures and conditions are read from (see sources.yaml).
PageSource = Literal["usfs-ltbmu", "usfs-tnf", "usfs-htnf", "nvparks-tahoe", "trta"]

# Lake Tahoe basin plus Truckee. Anything outside is out of scope.
TAHOE_BBOX = {"lat_min": 38.6, "lat_max": 39.5, "lon_min": -120.45, "lon_max": -119.75}


class Strict(BaseModel):
    model_config = ConfigDict(extra="forbid", frozen=True)


class LatLon(Strict):
    lat: float
    lon: float
    name: str | None = None

    def in_tahoe(self) -> bool:
        b = TAHOE_BBOX
        return b["lat_min"] <= self.lat <= b["lat_max"] and b["lon_min"] <= self.lon <= b["lon_max"]


class Trail(Strict):
    id: str = Field(pattern=r"^[a-z0-9]+(-[a-z0-9]+)*$")
    name: str = Field(min_length=1)
    trailhead: LatLon
    high_point: LatLon | None = None
    elevation_min_ft: int = Field(ge=3000, le=11000)
    elevation_max_ft: int = Field(ge=3000, le=11000)
    aspect: Aspect
    land_manager: str = Field(min_length=1)
    official_status_url: HttpUrl
    official_info_url: HttpUrl | None = None
    activities: tuple[Activity, ...] = Field(min_length=1)
    closure_keywords: tuple[str, ...] = Field(min_length=1)
    trta_segment: str | None = None  # div id on the TRTA conditions page, e.g. "TCtoBrockway"
    status_sources: tuple[PageSource, ...] = ()
    sources: tuple[HttpUrl, ...] = Field(min_length=1)
    notes: str | None = None
    confirmed: bool = False

    @model_validator(mode="after")
    def _check(self) -> Trail:
        if self.elevation_min_ft > self.elevation_max_ft:
            raise ValueError(f"{self.id}: elevation_min_ft > elevation_max_ft")
        for point in (self.trailhead, self.high_point):
            if point is not None and not point.in_tahoe():
                raise ValueError(f"{self.id}: {point} is outside the Tahoe bounding box")
        if self.trta_segment and "trta" not in self.status_sources:
            raise ValueError(f"{self.id}: has trta_segment but 'trta' is not in status_sources")
        if any(k != k.lower() or not k.strip() for k in self.closure_keywords):
            raise ValueError(f"{self.id}: closure_keywords must be non-empty lowercase")
        return self


class Claim(Strict):
    """One cited fact. statement is generated by a rule; quote is the raw value from the source."""

    kind: Literal["closure", "snow", "precip", "conditions", "forecast"]
    statement: str = Field(min_length=1)
    source_name: str = Field(min_length=1)
    source_url: HttpUrl
    fetched_at: AwareDatetime
    quote: str = Field(min_length=1)
    observed_at: AwareDatetime | None = None


class Missing(Strict):
    """A gap: what we needed, and the URL we tried (so even 'unknown' links somewhere)."""

    what: str = Field(min_length=1)
    tried_url: HttpUrl


class TrailLine(Strict):
    trail_id: str
    trail_name: str
    date: dt.date
    status: Status
    claims: tuple[Claim, ...] = ()  # the reasons for status
    context: tuple[Claim, ...] = ()  # other cited facts, not decisive
    missing: tuple[Missing, ...] = ()
    forecast: Claim | None = None

    @model_validator(mode="after")
    def _cited(self) -> TrailLine:
        if self.status == "unknown":
            if not self.missing:
                raise ValueError("an unknown line must say what is missing")
        elif not self.claims:
            raise ValueError(f"status {self.status!r} needs at least one cited claim")
        if any(c.kind == "forecast" for c in self.claims + self.context):
            raise ValueError("forecasts are context only and go in the forecast field")
        if self.forecast is not None and self.forecast.kind != "forecast":
            raise ValueError("forecast must be a forecast claim")
        return self


class TrailsFile(Strict):
    trails: tuple[Trail, ...]

    @model_validator(mode="after")
    def _unique(self) -> TrailsFile:
        ids = [t.id for t in self.trails]
        if len(ids) != len(set(ids)):
            raise ValueError("duplicate trail ids")
        return self
